#!/usr/bin/env python3
"""Generate experiments/20261112-149-leaf-v2/runs/registered-pins.json from the committed run files (issue #203).

HASH LEVEL, NOT A PROOF, NOT AUTHENTICATION. The pin is a committed list: it binds "registered run" to the
bytes the repository holds for run 1, run 2 and run 3 of the #149 leaf-v2 experiment. Anyone who can change
the repository can change the pin together with the run files; the pin is only as good as the repository's
history.

For each registered run it lists the SHA-256 of every file the leaf-v2 readers consume that exists in that
run directory (blocks.jsonl, run-meta.json, leaves-v2.json), and the SHA-256 of the two committed compare
files summarise.py consumes. No timestamp, sorted keys: a second run reproduces the file byte for byte.

Usage (from the top of the tree):
  make_pins.py            write the pin file
  make_pins.py --stdout   print the pin file, write nothing (for the reproducibility check)
  make_pins.py --check    exit 0 iff the committed pin file equals the regeneration
"""
import hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "experiments/20261112-149-leaf-v2/runs"
OUT = RUNS / "registered-pins.json"
REGISTERED_RUNS = ("run1", "run2", "run3")
CONSUMED = ("blocks.jsonl", "leaves-v2.json", "run-meta.json")
COMPARE_FILES = ("compare-run1-run2.json", "compare-run1-run3.json")


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def doc():
    runs = {}
    for run in REGISTERED_RUNS:
        d = RUNS / run
        runs[run] = {name: sha(d / name) for name in CONSUMED if (d / name).is_file()}
    return dict(
        note="registered-run pin for experiments/20261112-149-leaf-v2 (issue #203). A committed list that binds "
             "'registered run' to what the repository holds. NOT authentication: no signature, timestamp or attested "
             "runner; anyone who can change the repository can change this file together with the run files. "
             "Generated by experiments/20261114-203-leafv2-registered-pin/make_pins.py from the committed files.",
        consumed_names=list(CONSUMED),
        runs=runs,
        compare_files={name: sha(RUNS / name) for name in COMPARE_FILES},
        hash="sha256",
        version=1)


def text():
    return json.dumps(doc(), indent=1, sort_keys=True) + "\n"


def main(args):
    t = text()
    if "--stdout" in args:
        sys.stdout.write(t)
        return 0
    if "--check" in args:
        same = OUT.exists() and OUT.read_text() == t
        print("registered-pins.json", "matches the regeneration" if same else "DIFFERS from the regeneration")
        return 0 if same else 1
    OUT.write_text(t)
    print("wrote", OUT.relative_to(ROOT), hashlib.sha256(t.encode()).hexdigest())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
