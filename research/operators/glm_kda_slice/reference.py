#!/usr/bin/env python3
"""Independent exact-rational recurrence and fixed two-token circuit fixture.
No torch/kernel equivalence claim. Inputs are POST exp / query scaling.
"""
from fractions import Fraction as Q
from pathlib import Path
import json
P = 2**64 - 2**32 + 1

def reference(state, tokens):
    outputs=[]
    for d,k,v,b,q in tokens:
        dec=[s*x for s,x in zip(state,d)]
        memory=sum(s*x for s,x in zip(dec,k))
        delta=(v-memory)*b
        state=[s+x*delta for s,x in zip(dec,k)]
        outputs.append(sum(s*x for s,x in zip(state,q)))
    return state,outputs

state=[Q(1,2),Q(-1,4)]
tokens=[([Q(1,2),Q(1,4)],[Q(1,2),Q(-1,2)],Q(3,4),Q(1,2),[Q(1,2),Q(1,4)]),
        ([Q(1,4),Q(1,2)],[Q(-1,4),Q(1,2)],Q(-1,2),Q(3,4),[Q(1,4),Q(-1,2)])]
expected,outputs=reference(state,tokens)
# Separate graph lowering, with every add/sub stored as x*1 and constrained
# by an affine row. Every reused operand has an equality, not a host-only copy.
table=[];coords=[];wires=[];affines=[]
def val(x): return table[x[1]][x[0]] if isinstance(x,tuple) else x
def gate(a,b):
    col=len(table);table.append([val(a),val(b),val(a)*val(b)])
    for row,x in enumerate((a,b)):
        if isinstance(x,tuple): wires.append((*x,row,col))
        else: coords.append((row,col,x))
    return (2,col)
def linear(terms):
    value=sum(val(x)*c for x,c in terms);col=len(table)
    table.append([value,Q(1),value]);coords.append((1,col,Q(1)))
    affines.append([(0,col,Q(1))]+[(x[0],x[1],-c) for x,c in terms])
    return (2,col)
s=state;got=[];boundaries=[]
for d,k,v,b,q in tokens:
    dec=[gate(s[i],d[i]) for i in range(2)]
    mem=linear([(gate(dec[i],k[i]),Q(1)) for i in range(2)])
    # v is a public gate input, not an unbound affine constant.
    vv=gate(v,Q(1));diff=linear([(vv,Q(1)),(mem,Q(-1))])
    delta=gate(diff,b)
    s=[linear([(dec[i],Q(1)),(gate(k[i],delta),Q(1))]) for i in range(2)]
    out=linear([(gate(s[i],q[i]),Q(1)) for i in range(2)])
    got.append(val(out));coords.append((*out,outputs[len(got)-1]));boundaries.append(s)
assert [val(x) for x in s]==expected and got==outputs
for x,e in zip(s,expected):coords.append((*x,e))
assert len(table)<=32 and len(coords)<=64 and len(wires)<=64 and len(affines)<=64
# Dyadic fixture: Python binary64 gives exactly the rational result here.
fstate,fout=reference([float(x) for x in state], [([float(x) for x in d],[float(x) for x in k],float(v),float(b),[float(x) for x in q]) for d,k,v,b,q in tokens])
assert list(map(Q,fstate))==expected and list(map(Q,fout))==outputs
enc=lambda x: (x.numerator*pow(x.denominator,-1,P))%P
f=lambda x: 'F{'+str(enc(x))+'ULL}'
lines=['// Generated by reference.py; deterministic, synthetic, no checkpoint weights.', 'Table fixture(){Table t(1,3,32);']
for col,values in enumerate(table):
    for row,x in enumerate(values):lines.append(f't.set({row},{col},E::from({f(x)}));')
lines+=['return t;}','std::vector<Coordinate> coordinates={'+','.join('{'+f'{r},{c},{f(v)}'+'}' for r,c,v in coords)+'};', 'std::vector<WireEquality> wires={'+','.join('{'+','.join(map(str,w))+'}' for w in wires)+'};', 'std::vector<AffineRelation> relations={'+','.join('{{'+','.join('{'+f'{r},{c},{f(v)}'+'}' for r,c,v in a)+'},F{0}}' for a in affines)+'};']
here=Path(__file__).resolve().parent
(here/'fixture.h').write_text('\n'.join(lines)+'\n')
(here/'reference.json').write_text(json.dumps(dict(arithmetic='exact rational mapped into Goldilocks; NOT fixed point',state=list(map(str,expected)),outputs=list(map(str,outputs)),gates=len(table),coordinates=len(coords),wires=len(wires),affine_rows=len(affines)),indent=2)+'\n')
print('reference: PASS; two tokens, key dimension 2, value dimension 1; rational and dyadic binary64 agree')
