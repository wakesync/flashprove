#!/usr/bin/env python3
"""Pinned integer tables for the M2 head's verifier-recomputed steps.

The three F = 12 tables are the operators lane's files (PR #67, format
`flashprove-qwen-integer-tables-v1`), copied byte for byte: 4,096 signed 64-bit little-endian rows,
no header, row = floor(X / 16) + 2048 for an input integer X at 2^12, domain [-8, 8), output at 2^12.
This lane does not generate them and does not fork the format. Regenerating them from first
principles is that lane's test (its tables.py). What is checked here:
  * each file's SHA-256 equals the value recorded below (the operators lane's manifest values);
  * tables/pinned_f12.h, the C++ copy that prover and verifier compile in, equals the files;
  * writing the header twice gives identical bytes.
Usage: tables.py check | tables.py write
"""
import hashlib, pathlib, struct, sys
here = pathlib.Path(__file__).resolve().parent
TAB = here / 'tables'
PINNED = {  # name -> (file, sha256), from PR #67's manifest.json
    'silu': ('silu-f12.i64le', 'cb2ceb05c7a1292a064e8d6d63cf9b63926db1122ea19663faecee21752bf8e9'),
    'sigmoid': ('sigmoid-f12.i64le', '19057d5fd13d67d8895e7b31f9b0d8c55eb75802857f8ae8b5deae67ab9202d5'),
    'decay_one': ('decay-one-f12.i64le', 'ffd373e621ca994094bf876d684498580532286cc28dd005a79524831c3daedb'),
}
ROWS = 4096

def load(name):
    f, want = PINNED[name]
    raw = (TAB / f).read_bytes()
    assert len(raw) == 8 * ROWS, f'{f}: not {ROWS} rows'
    got = hashlib.sha256(raw).hexdigest()
    assert got == want, f'{f}: sha256 {got} is not the pinned {want}'
    return list(struct.unpack(f'<{ROWS}q', raw))

def header():
    out = ['// Generated by tables.py from the pinned .i64le files; do not edit.', '// SPDX-License-Identifier: Apache-2.0', '#pragma once', '#include <cstdint>', 'namespace m2tables {',
           f'constexpr int ROWS = {ROWS};  // row = floor(X / 16) + 2048, X at 2^12 in [-8, 8); output at 2^12']
    for name in sorted(PINNED):
        f, sha = PINNED[name]
        vals = load(name)
        out.append(f'// {f}, sha256 {sha}')
        out.append(f'inline const int64_t {name}_f12[ROWS] = {{')
        for i in range(0, ROWS, 32): out.append(','.join(str(v) for v in vals[i:i + 32]) + ',')
        out.append('};')
    out.append('}  // namespace m2tables')
    return '\n'.join(out) + '\n'

def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'check'
    a, b = header(), header()
    assert a == b, 'two builds of the header differ'
    path = TAB / 'pinned_f12.h'
    if mode == 'write':
        path.write_text(a)
    assert path.read_text() == a, 'tables/pinned_f12.h is not what the pinned files give'
    for name in sorted(PINNED):
        v = load(name)
        print(f'{PINNED[name][0]}: sha256 ok, rows {len(v)}, min {min(v)}, max {max(v)}')
    print('pinned_f12.h: sha256', hashlib.sha256(a.encode()).hexdigest())
    print('tables: ok')

if __name__ == '__main__':
    main()
