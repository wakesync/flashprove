#!/usr/bin/env python3
"""Integer-only optional rotary artifact, separate manifest from nonlinear v1."""
import argparse
import hashlib
import json
import math
import struct
from tables import HERE, Q, nearest


def atan_inverse(d):
    power=Q//d
    total=0
    for k in range(256):
        term=power//(2*k+1)
        total += term if k%2==0 else -term
        power //= d*d
    return total


def sincos(phase, pi):
    x=(phase+pi)%(2*pi)-pi
    sin_term=sin_sum=x
    cos_term=cos_sum=Q
    for k in range(1,129):
        sin_term=(-sin_term*x*x)//(Q*Q*(2*k)*(2*k+1))
        cos_term=(-cos_term*x*x)//(Q*Q*(2*k-1)*(2*k))
        sin_sum+=sin_term
        cos_sum+=cos_term
    return cos_sum,sin_sum


def generate():
    pi=16*atan_inverse(5)-4*atan_inverse(239)
    frequencies=[]
    for j in range(32):
        # floor(Q*theta^(-j/32)), five exact integer square roots.
        v=pow(Q,32)//pow(10,7*j)
        for _ in range(5):v=math.isqrt(v)
        frequencies.append(v)
    rows={f:[] for f in (12,14,16)}
    for t in range(1024):
        for omega in frequencies:
            c,s=sincos(t*omega,pi)
            for f in rows:
                rows[f].extend((nearest(c*(1<<f),Q),nearest(s*(1<<f),Q)))
    files={}
    manifest=dict(format='flashprove-qwen-rotary-v1',theta=10000000,head_dimension=256,
                  rotary_dimension=64,positions=1024,pairs=32,
                  layout='row-major [position][pair][cos,sin], signed little-endian int64, no header',
                  pairs_rule='(j,j+32), j=0..31; coordinates64..255 unchanged',
                  generator='Q256 Machin pi, floor32nd-root frequency, range-reduced 128-term sin/cos',
                  rounding='nearest ties-to-even of Q256 integer approximation',tables=[])
    header='// Generated by rotary_tables.py; do not edit.\n#pragma once\n#include <cstdint>\nnamespace qrotary {\n'
    for f,vals in rows.items():
        name=f'rotary-f{f}.i64le'
        data=struct.pack('<65536q',*vals);files[name]=data
        manifest['tables'].append(dict(file=name,F=f,words=65536,output_scale=1<<f,sha256=hashlib.sha256(data).hexdigest()))
        header+=f'inline const int64_t f{f}[65536] = {{\n'
        header+='\n'.join(','.join(str(v) for v in vals[i:i+64])+',' for i in range(0,len(vals),64))+'\n};\n'
    header+='}\n'
    files['rotary-pinned.h']=header.encode()
    files['rotary-manifest.json']=(json.dumps(manifest,indent=2,sort_keys=True)+'\n').encode()
    return files


def load(f):
    return struct.unpack('<65536q',(HERE/'tables'/f'rotary-f{f}.i64le').read_bytes())


def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    files=generate()
    for name,data in files.items():
        path=HERE/'tables'/name
        if args.check:assert path.read_bytes()==data,name
        else:path.write_bytes(data)
    print(json.dumps(dict(regenerated_equal=args.check,manifest_sha256=hashlib.sha256(files['rotary-manifest.json']).hexdigest())))


if __name__=='__main__':main()
