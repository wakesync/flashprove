#!/usr/bin/env python3
"""Pinned integer tables. Standard library only; no floating point used here."""
import argparse
import hashlib
import json
import math
import pathlib
import struct

BITS = 256
Q = 1 << BITS
HERE = pathlib.Path(__file__).resolve().parent
NAMES = ('silu', 'sigmoid', 'softplus', 'decay-half', 'decay-one', 'decay-two', 'rsqrt', 'l2-128')


def nearest(n, d):
    """Exact nearest integer with ties to even, including negative n."""
    q, r = divmod(n, d)
    return q + int(2*r > d or (2*r == d and q % 2 != 0))


def expq(x):
    """Q256 arithmetic algorithm, not a claim of correctly rounded real exp.

    Reduce x by 16 using floor, sum 128 Taylor terms, then square four times.
    Negative arguments use the reciprocal of the positive-argument result.
    All multiplications and divisions round down. Supported |x| <= 32 Q.
    """
    assert abs(x) <= 32*Q
    if x < 0:
        return Q*Q // expq(-x)
    t = s = Q
    y = x // 16
    for k in range(1, 129):
        t = t*y // (Q*k)
        s += t
    for _ in range(4):
        s = s*s // Q
    return s


def atanh_logq(x):
    """log(x), x/Q in [1,2], via 256 odd atanh terms, integer floors."""
    assert Q <= x <= 2*Q
    z = (x-Q)*Q // (x+Q)
    z2 = z*z // Q
    t = z
    s = 0
    for k in range(256):
        s += t // (2*k+1)
        t = t*z2 // Q
    return 2*s


LN2 = atanh_logq(2*Q)


def logq(x):
    assert x >= Q
    e = x.bit_length() - 1 - BITS
    return atanh_logq(x >> e) + e*LN2


def root_round(n, d):
    """Nearest-even sqrt(n/d) using exact integer comparison."""
    q = math.isqrt(n // d)
    delta = 4*n - d*(2*q+1)**2
    return q + int(delta > 0 or (delta == 0 and q % 2))


def generate():
    rows = {(name, f): [] for name in NAMES for f in (12, 14, 16)}
    for i in range(4096):
        x = (i-2048)*(Q//256)
        sig = Q*Q // (Q+expq(-x))
        sp = logq(Q+expq(x))
        values = [x*sig//Q, sig, sp, expq(-sp//2), expq(-sp), expq(-2*sp)]
        for f in (12, 14, 16):
            for name, v in zip(NAMES[:6], values):
                rows[name, f].append(nearest(v*(1 << f), Q))
            for name, d in [('rsqrt', 1), ('l2-128', 128)]:
                rows[name, f].append(root_round((1 << (2*f))*1024, d*(i+256)))
    manifest = {'format': 'flashprove-qwen-integer-tables-v1',
                'generator': 'tables.py: Q256 integer exp/log v1; exact integer reciprocal-root rounding',
                'rounding': 'nearest ties-to-even of the integer Q256 approximation; rsqrt exact rational root',
                'runtime_float': False, 'tables': []}
    files = {}
    for (name, f), values in sorted(rows.items()):
        filename = f'{name}-f{f}.i64le'
        data = struct.pack('<4096q', *values)
        files[filename] = data
        nonlinear = name not in ('rsqrt', 'l2-128')
        manifest['tables'].append(dict(file=filename, name=name, F=f, rows=4096,
            encoding='signed little-endian int64, headerless', output_scale=1 << f,
            input_offset_numerator=-2048 if nonlinear else 256,
            input_denominator=256 if nonlinear else 1024,
            domain='[-8,8)' if nonlinear else '[1/4,17/4)',
            sha256=hashlib.sha256(data).hexdigest()))
    files['manifest.json'] = (json.dumps(manifest, indent=2, sort_keys=True)+'\n').encode()
    return files


def load(name, f):
    return struct.unpack('<4096q', (HERE/'tables'/f'{name}-f{f}.i64le').read_bytes())


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    files = generate()
    for name, data in files.items():
        path = HERE/'tables'/name
        if args.check:
            assert path.read_bytes() == data, name
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_bytes(data)
    # C++ constants are a verifier-owned copy, checked against the binary artifacts.
    header = '// Generated by tables.py; do not edit.\n#pragma once\n#include <cstdint>\nnamespace qtables {\n'
    for f in (12, 14, 16):
        for name in NAMES:
            vals = struct.unpack('<4096q', files[f'{name}-f{f}.i64le'])
            header += 'inline const int64_t '+name.replace('-', '_')+'_f'+str(f)+'[4096] = {\n'
            header += '\n'.join(','.join(str(v) for v in vals[j:j+32])+',' for j in range(0,4096,32))+'\n};\n'
    header += '}\n'
    path = HERE/'tables'/'pinned.h'
    if args.check:
        assert path.read_text() == header
    else:
        path.write_text(header)
    print(json.dumps({'files':len(files), 'rows':24*4096, 'manifest_sha256':hashlib.sha256(files['manifest.json']).hexdigest(), 'regenerated_equal':args.check}))


if __name__ == '__main__':
    main()
