#!/usr/bin/env python3
"""Validate research/results.yaml and regenerate the README results block and CLAIMS.md.

  python3 scripts/update-results.py          validate, then rewrite README.md between the markers and CLAIMS.md
  python3 scripts/update-results.py --check  validate; exit 1 if README.md's block or CLAIMS.md is out of date

The README block and CLAIMS.md are rendered from the prose fields. The numeric
`metrics` are validated (types, units, spread, hardware key, commit on this
branch's history, source path present at that commit) so a later plotting script
can trust them. It does NOT check that a value appears in its source file: that
match is the reviewer's job. Nothing here draws charts.

CLAIMS.md carries no date or commit stamp, so it only changes when results.yaml
does (the loop's results sync may then touch README.md alone).
"""
import datetime
import os
import re
import subprocess
import sys

import yaml

ROOT = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip()
SRC = os.path.join(ROOT, "research", "results.yaml")
README = os.path.join(ROOT, "README.md")
BEGIN = "<!-- results:begin (generated by scripts/update-results.py from research/results.yaml; edit that file) -->"
END = "<!-- results:end -->"

STATUSES = {"reproduced", "measured", "negative", "in progress", "done"}
STATS = {"single", "median", "mean", "max", "count"}
UNITS = {"s", "B", "KiB", "MiB", "USD", "count", "exit_code", "abs_diff", "fraction", "ratio", "int"}
REPLICATION = {"replicated", "unreplicated", "n/a"}
CLAIMS = os.path.join(ROOT, "CLAIMS.md")
METRIC_KEYS = {"name", "series", "arm", "stat", "value", "unit", "total", "n", "spread",
               "hardware", "date", "commit", "source", "note"}
REQUIRED = {"name", "stat", "value", "unit", "n", "spread", "hardware", "date", "commit", "source"}
SPREAD_KEYS = {"sd", "min", "max", "resolution"}
SHA = re.compile(r"^[0-9a-f]{40}$")


def git_ok(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True).returncode == 0


def num(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def tracked(path):
    # a repo path that exists in the checkout and is tracked by git (not a stray local file)
    return isinstance(path, str) and os.path.exists(os.path.join(ROOT, path)) and git_ok("ls-files", "--error-unmatch", "--", path)


def resolve_replicated_by(rid, ref, ids):
    # replicated_by must point at a receipt: another result id in this file, or a tracked path
    if not isinstance(ref, str) or not ref:
        return f"{rid}: replicated needs replicated_by (another result id or a tracked repo path)"
    if ref == rid:
        return f"{rid}: replicated_by points at itself"
    if ref in ids or tracked(ref):
        return None
    return f"{rid}: replicated_by {ref!r} is neither a result id in results.yaml nor a tracked repo path"


def validate(doc):
    errs = []
    all_ids = {r.get("id") for r in doc.get("results") or []}
    if doc.get("schema_version") != 1:
        errs.append("schema_version must be 1")
    hw = doc.get("hardware") or {}
    ids = set()
    for r in doc.get("results") or []:
        rid = r.get("id", "?")
        if rid in ids:
            errs.append(f"{rid}: duplicate id")
        ids.add(rid)
        for k in ("title", "status", "summary", "conditions", "evidence"):
            if not r.get(k):
                errs.append(f"{rid}: missing {k}")
        if r.get("status") not in STATUSES:
            errs.append(f"{rid}: status {r.get('status')!r} not in {sorted(STATUSES)}")
        rep = r.get("replication")
        if rep not in REPLICATION:
            errs.append(f"{rid}: replication {rep!r} not in {sorted(REPLICATION)}")
        elif rep == "replicated" and (e := resolve_replicated_by(rid, r.get("replicated_by"), all_ids)):
            errs.append(e)
        elif rep == "n/a" and r.get("status") not in ("done", "in progress"):
            errs.append(f"{rid}: replication n/a is only for done / in progress rows")
        for p in r.get("evidence") or []:
            if not os.path.exists(os.path.join(ROOT, p)):
                errs.append(f"{rid}: evidence path missing: {p}")
        names = set()
        for m in r.get("metrics") or []:
            where = f"{rid}.{m.get('name', '?')}"
            if m.get("name") in names:
                errs.append(f"{where}: duplicate metric name")
            names.add(m.get("name"))
            if missing := REQUIRED - m.keys():
                errs.append(f"{where}: missing {sorted(missing)}")
            if extra := m.keys() - METRIC_KEYS:
                errs.append(f"{where}: unknown keys {sorted(extra)}")
            if not num(m.get("value")):
                errs.append(f"{where}: value must be a number")
            if m.get("unit") not in UNITS:
                errs.append(f"{where}: unit {m.get('unit')!r} not in {sorted(UNITS)}")
            if m.get("stat") not in STATS:
                errs.append(f"{where}: stat {m.get('stat')!r} not in {sorted(STATS)}")
            if not (isinstance(m.get("n"), int) and m["n"] >= 1):
                errs.append(f"{where}: n must be an integer >= 1")
            if "total" in m and not (isinstance(m["total"], int) and num(m.get("value")) and m["total"] >= m["value"]):
                errs.append(f"{where}: total must be an integer >= value")
            sp = m.get("spread")
            if sp is not None:
                if not isinstance(sp, dict) or not sp or sp.keys() - SPREAD_KEYS:
                    errs.append(f"{where}: spread must be null or a map of {sorted(SPREAD_KEYS)}")
                elif any(v is not None and not num(v) for v in sp.values()):
                    errs.append(f"{where}: spread values must be numbers or null")
                elif num(sp.get("min")) and num(sp.get("max")) and num(m.get("value")) and m["stat"] in ("median", "mean") \
                        and not sp["min"] <= m["value"] <= sp["max"]:
                    errs.append(f"{where}: value outside [min, max]")
            if m.get("stat") in ("median", "mean") and m.get("n", 0) >= 2 and sp is None and "note" not in m:
                errs.append(f"{where}: a {m['stat']} over n >= 2 needs a spread, or a note saying why it has none")
            if m.get("hardware") not in hw:
                errs.append(f"{where}: hardware {m.get('hardware')!r} not defined")
            d = m.get("date")
            if isinstance(d, datetime.date):
                d = d.isoformat()
            if not (isinstance(d, str) and re.match(r"^\d{4}-\d{2}-\d{2}$", d)):
                errs.append(f"{where}: date must be YYYY-MM-DD")
            c = str(m.get("commit", ""))
            if not SHA.match(c):
                errs.append(f"{where}: commit must be a full 40-hex SHA")
            elif not git_ok("merge-base", "--is-ancestor", c, "HEAD"):
                errs.append(f"{where}: commit {c[:12]} is not in this branch's history")
            else:
                src = m.get("source")
                if src == "commit-message":
                    if "note" not in m:
                        errs.append(f"{where}: source commit-message needs a note (it is not a file receipt)")
                elif not git_ok("cat-file", "-e", f"{c}:{src}"):
                    errs.append(f"{where}: source {src} does not exist at {c[:12]}")
    return errs


def cell(s):
    return str(s).replace("|", "\\|").strip()


def status_cell(r):
    s = r["status"]
    if r.get("replication") == "unreplicated":
        s += ", unreplicated"
    return s + (f" {r['status_note']}" if r.get("status_note") else "")


CLAIMS_HEAD = """# Claims ledger

Generated by `scripts/update-results.py` from [research/results.yaml](research/results.yaml); do not edit by hand.
Checked by `scripts/check-claims.py` (every README results row has a row here, evidence paths exist, replication
labels agree).

Every public statement about this fork's results must map to a row here, and every row to evidence on `main`.
`unreplicated` means one lane measured it and no separate lane has reproduced it with a receipt in a file
(research standard 5); such a number is not a headline. `replicated` names the receipt: another row id or a
tracked file, which both scripts resolve (they check that it exists, not what it says).

| id | Claim | Status | Replication | Evidence | PR |
|---|---|---|---|---|---|
"""


def render_claims(doc):
    rows = []
    ids = {r["id"] for r in doc["results"]}
    for r in doc["results"]:
        by = r.get("replicated_by")
        if by:
            by = f"`{by}`" if by in ids else f"[{by}]({by})"
            by += f"; {r['replication_note']}" if r.get("replication_note") else ""
        rep = r["replication"] + (f" ({by})" if by else "")
        ev = ", ".join(f"[{p}]({p})" for p in r["evidence"])
        pr = f"#{r['pr']}" if r.get("pr") else "-"
        pr += f" ({r['pr_note']})" if r.get("pr_note") else ""
        rows.append("| " + " | ".join(cell(x) for x in (
            f"`{r['id']}`", f"{r['title']}: {r['summary']}", status_cell(r), rep, ev, pr)) + " |")
    return CLAIMS_HEAD + "\n".join(rows) + "\n"


def render(doc):
    # Stamp with the main commit the evidence is read against, not the branch
    # head (which changes again when the regenerated README is committed).
    base = "origin/main" if git_ok("rev-parse", "--verify", "-q", "origin/main") else "HEAD"
    head = git_out("rev-parse", "--short=8", git_out("merge-base", "HEAD", base))
    date = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    rows = ["| Result | Status | Key number | n + conditions | Evidence |", "|---|---|---|---|---|"]
    for r in doc["results"]:
        status = status_cell(r)
        ev = r["evidence"][0]
        label = ev[: -len("README.md")] if ev.endswith("/README.md") else ev
        link = f"[{label}]({ev})" + (r.get("evidence_note") or "")
        rows.append("| " + " | ".join(cell(x) for x in (r["title"], status, r["summary"], r["conditions"], link)) + " |")
    stamp = f"_Last regenerated from `research/results.yaml` on {date} (UTC), against main `{head}`._"
    return "\n".join([BEGIN, *rows, "", stamp, END])


def git_out(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True, check=True).stdout.strip()


def strip_stamp(block):
    # --check ignores the stamp on purpose: a stale "against main" stamp is the loop
    # sensor's job (readme_stale), not a content error in this branch.
    return re.sub(r"^_Last regenerated .*_$", "", block, flags=re.M)


def main():
    check = "--check" in sys.argv[1:]
    doc = yaml.safe_load(open(SRC))
    errs = validate(doc)
    if errs:
        print("results.yaml: INVALID", *errs, sep="\n  ", file=sys.stderr)
        return 1
    text = open(README).read()
    if BEGIN not in text or END not in text:
        print("README.md: results markers not found", file=sys.stderr)
        return 1
    pre, rest = text.split(BEGIN, 1)
    old, post = rest.split(END, 1)
    new = render(doc)
    n_metrics = sum(len(r.get("metrics") or []) for r in doc["results"])
    claims = render_claims(doc)
    if check:
        if strip_stamp(BEGIN + old + END) != strip_stamp(new):
            print("README.md results block is stale: run python3 scripts/update-results.py", file=sys.stderr)
            return 1
        if not os.path.exists(CLAIMS) or open(CLAIMS).read() != claims:
            print("CLAIMS.md is stale or missing: run python3 scripts/update-results.py", file=sys.stderr)
            return 1
        print(f"update-results: ok ({len(doc['results'])} results, {n_metrics} metrics, README and CLAIMS.md in sync)")
        return 0
    open(README, "w").write(pre + new + post)
    open(CLAIMS, "w").write(claims)
    print(f"update-results: wrote README block and CLAIMS.md ({len(doc['results'])} results, {n_metrics} metrics)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
