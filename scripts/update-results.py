#!/usr/bin/env python3
"""Validate research/results.yaml and regenerate the README results block.

  python3 scripts/update-results.py          validate, then rewrite README.md between the markers
  python3 scripts/update-results.py --check  validate; exit 1 if README.md is out of date

The README block is rendered from the prose fields. The numeric `metrics` are
validated (types, units, spread, hardware key, commit on this branch's history,
source path present at that commit) so a later plotting script can trust them.
Nothing here draws charts.
"""
import datetime
import os
import re
import subprocess
import sys

import yaml

ROOT = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip()
SRC = os.path.join(ROOT, "research", "results.yaml")
README = os.path.join(ROOT, "README.md")
BEGIN = "<!-- results:begin (generated by scripts/update-results.py from research/results.yaml; edit that file) -->"
END = "<!-- results:end -->"

STATUSES = {"reproduced", "measured", "negative", "in progress", "done"}
STATS = {"single", "median", "mean", "max", "count"}
UNITS = {"s", "B", "MiB", "USD", "count", "exit_code", "abs_diff"}
METRIC_KEYS = {"name", "series", "arm", "stat", "value", "unit", "total", "n", "spread",
               "hardware", "date", "commit", "source", "note"}
REQUIRED = {"name", "stat", "value", "unit", "n", "spread", "hardware", "date", "commit", "source"}
SPREAD_KEYS = {"sd", "min", "max", "resolution"}
SHA = re.compile(r"^[0-9a-f]{40}$")


def git_ok(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True).returncode == 0


def num(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def validate(doc):
    errs = []
    if doc.get("schema_version") != 1:
        errs.append("schema_version must be 1")
    hw = doc.get("hardware") or {}
    ids = set()
    for r in doc.get("results") or []:
        rid = r.get("id", "?")
        if rid in ids:
            errs.append(f"{rid}: duplicate id")
        ids.add(rid)
        for k in ("title", "status", "summary", "conditions", "evidence"):
            if not r.get(k):
                errs.append(f"{rid}: missing {k}")
        if r.get("status") not in STATUSES:
            errs.append(f"{rid}: status {r.get('status')!r} not in {sorted(STATUSES)}")
        for p in r.get("evidence") or []:
            if not os.path.exists(os.path.join(ROOT, p)):
                errs.append(f"{rid}: evidence path missing: {p}")
        names = set()
        for m in r.get("metrics") or []:
            where = f"{rid}.{m.get('name', '?')}"
            if m.get("name") in names:
                errs.append(f"{where}: duplicate metric name")
            names.add(m.get("name"))
            if missing := REQUIRED - m.keys():
                errs.append(f"{where}: missing {sorted(missing)}")
            if extra := m.keys() - METRIC_KEYS:
                errs.append(f"{where}: unknown keys {sorted(extra)}")
            if not num(m.get("value")):
                errs.append(f"{where}: value must be a number")
            if m.get("unit") not in UNITS:
                errs.append(f"{where}: unit {m.get('unit')!r} not in {sorted(UNITS)}")
            if m.get("stat") not in STATS:
                errs.append(f"{where}: stat {m.get('stat')!r} not in {sorted(STATS)}")
            if not (isinstance(m.get("n"), int) and m["n"] >= 1):
                errs.append(f"{where}: n must be an integer >= 1")
            if "total" in m and not (isinstance(m["total"], int) and num(m.get("value")) and m["total"] >= m["value"]):
                errs.append(f"{where}: total must be an integer >= value")
            sp = m.get("spread")
            if sp is not None:
                if not isinstance(sp, dict) or not sp or sp.keys() - SPREAD_KEYS:
                    errs.append(f"{where}: spread must be null or a map of {sorted(SPREAD_KEYS)}")
                elif any(v is not None and not num(v) for v in sp.values()):
                    errs.append(f"{where}: spread values must be numbers or null")
                elif num(sp.get("min")) and num(sp.get("max")) and num(m.get("value")) and m["stat"] in ("median", "mean") \
                        and not sp["min"] <= m["value"] <= sp["max"]:
                    errs.append(f"{where}: value outside [min, max]")
            if m.get("stat") in ("median", "mean") and m.get("n", 0) >= 2 and sp is None and "note" not in m:
                errs.append(f"{where}: a {m['stat']} over n >= 2 needs a spread, or a note saying why it has none")
            if m.get("hardware") not in hw:
                errs.append(f"{where}: hardware {m.get('hardware')!r} not defined")
            d = m.get("date")
            if isinstance(d, datetime.date):
                d = d.isoformat()
            if not (isinstance(d, str) and re.match(r"^\d{4}-\d{2}-\d{2}$", d)):
                errs.append(f"{where}: date must be YYYY-MM-DD")
            c = str(m.get("commit", ""))
            if not SHA.match(c):
                errs.append(f"{where}: commit must be a full 40-hex SHA")
            elif not git_ok("merge-base", "--is-ancestor", c, "HEAD"):
                errs.append(f"{where}: commit {c[:12]} is not in this branch's history")
            else:
                src = m.get("source")
                if src != "commit-message" and not git_ok("cat-file", "-e", f"{c}:{src}"):
                    errs.append(f"{where}: source {src} does not exist at {c[:12]}")
    return errs


def cell(s):
    return str(s).replace("|", "\\|").strip()


def render(doc):
    head = git_out("rev-parse", "--short=8", "HEAD")
    date = git_out("log", "-1", "--format=%cs", "HEAD")
    rows = ["| Result | Status | Key number | n + conditions | Evidence |", "|---|---|---|---|---|"]
    for r in doc["results"]:
        status = r["status"] + (f" {r['status_note']}" if r.get("status_note") else "")
        ev = r["evidence"][0]
        label = ev[: -len("README.md")] if ev.endswith("/README.md") else ev
        link = f"[{label}]({ev})" + (r.get("evidence_note") or "")
        rows.append("| " + " | ".join(cell(x) for x in (r["title"], status, r["summary"], r["conditions"], link)) + " |")
    stamp = f"_Last regenerated from `research/results.yaml` at branch commit `{head}` ({date})._"
    return "\n".join([BEGIN, *rows, "", stamp, END])


def git_out(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True, check=True).stdout.strip()


def strip_stamp(block):
    return re.sub(r"^_Last regenerated .*_$", "", block, flags=re.M)


def main():
    check = "--check" in sys.argv[1:]
    doc = yaml.safe_load(open(SRC))
    errs = validate(doc)
    if errs:
        print("results.yaml: INVALID", *errs, sep="\n  ", file=sys.stderr)
        return 1
    text = open(README).read()
    if BEGIN not in text or END not in text:
        print("README.md: results markers not found", file=sys.stderr)
        return 1
    pre, rest = text.split(BEGIN, 1)
    old, post = rest.split(END, 1)
    new = render(doc)
    n_metrics = sum(len(r.get("metrics") or []) for r in doc["results"])
    if check:
        if strip_stamp(BEGIN + old + END) != strip_stamp(new):
            print("README.md results block is stale: run python3 scripts/update-results.py", file=sys.stderr)
            return 1
        print(f"update-results: ok ({len(doc['results'])} results, {n_metrics} metrics, README in sync)")
        return 0
    open(README, "w").write(pre + new + post)
    print(f"update-results: wrote README block ({len(doc['results'])} results, {n_metrics} metrics)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
